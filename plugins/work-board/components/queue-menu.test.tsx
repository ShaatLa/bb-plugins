it("renders numbered rows and trash actions", async () => {
  state.queues = [{ threadId: "thr_example", entries: [entry(1), entry(2), entry(3)] }];
  render(<QueueMenu projectId="proj_example" />);
  fireEvent.pointerDown(screen.getByRole("button", { name: /Queue: next/ }), { button: 0, ctrlKey: false });
  const menu = await screen.findByRole("menu");
  expect(menu.querySelector('[data-icon="Play"]')).toBeTruthy();
  expect(within(menu).getByText("2")).toBeTruthy();
  expect(within(menu).getByText("3")).toBeTruthy();
  for (let n = 1; n <= 3; n++) {
    const button = within(menu).getByRole("button", { name: `Remove EXA-${n} from the queue` });
    expect(button.querySelector('[data-icon="Trash2"]')).toBeTruthy();
    fireEvent.click(button);
    await waitFor(() => expect(state.calls).toContainEqual(["queueRemove", { taskId: `task${n}`, actor: "owner" }]));
  }
  expect(menu.textContent).not.toMatch(/[↑↓×]/);
});
it("drops upward and reports refusal without changing order", async () => {
  state.queues = [{ threadId: "thr_example", entries: [entry(1), entry(2), entry(3)] }];
  render(<QueueMenu projectId="proj_example" />);
  fireEvent.pointerDown(screen.getByRole("button", { name: /Queue: next/ }), { button: 0, ctrlKey: false });
  const menu = await screen.findByRole("menu");
  const row = (n: number) => within(menu).getByRole("menuitem", { name: new RegExp(`EXA-${n}`) }).parentElement!;
  const transfer = { effectAllowed: "" };
  fireEvent.dragStart(row(3), { dataTransfer: transfer });
  fireEvent.dragOver(row(1), { dataTransfer: transfer });
  fireEvent.drop(row(1), { dataTransfer: transfer });
  await waitFor(() => expect(state.calls).toContainEqual(["queueMove", { taskId: "task3", position: 1, actor: "owner" }]));
  state.failure = true;
  fireEvent.dragStart(row(3), { dataTransfer: transfer });
  fireEvent.dragOver(row(1), { dataTransfer: transfer });
  fireEvent.drop(row(1), { dataTransfer: transfer });
  expect(await within(menu).findByText("Order refused")).toBeTruthy();
  expect(within(menu).getAllByRole("menuitem").map((e) => e.textContent?.slice(0, 5))).toEqual(["EXA-1", "EXA-2", "EXA-3"]);
});
it("keeps Radix arrow navigation and Enter selection", async () => {
  state.queues = [{ threadId: "thr_example", entries: [entry(1), entry(2), entry(3)] }];
  render(<QueueMenu projectId="proj_example" />);
  fireEvent.pointerDown(screen.getByRole("button", { name: /Queue: next/ }), { button: 0, ctrlKey: false });
  const menu = await screen.findByRole("menu");
  const items = within(menu).getAllByRole("menuitem");
  items[0]!.focus();
  fireEvent.keyDown(items[0]!, { key: "ArrowDown" });
  await waitFor(() => expect(document.activeElement).toBe(items[1]));
  items[2]!.focus();
  fireEvent.keyDown(items[2]!, { key: "ArrowDown", altKey: true });
  expect(state.calls).toHaveLength(0);
  items.forEach((item) => expect(item.getAttribute("aria-keyshortcuts")).toBe("Alt+ArrowUp Alt+ArrowDown Delete"));
  fireEvent.keyDown(items[2]!, { key: "Enter" });
  expect(state.go).toHaveBeenCalledWith({ kind: "task", taskKey: "EXA-3" });
  await waitFor(() => expect(screen.queryByRole("menu")).toBeNull());
});
