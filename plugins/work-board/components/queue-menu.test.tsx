// @vitest-environment jsdom
import { cleanup, fireEvent, render, screen, waitFor, within } from "@testing-library/react";
import { afterEach, expect, it, vi } from "vitest";
import { QueueMenu } from "./queue-menu";
const state = vi.hoisted(() => ({ queues: [] as any[], calls: [] as any[], failure: false, error: "", refresh: vi.fn(), go: vi.fn(), gate: null as Promise<void> | null }));
const sdk = { threads: { get: async ({ threadId }: { threadId: string }) => ({ title: threadId }), list: async () => [] } };
vi.mock("@get-bb/plugin-sdk/app", async (actual) => ({ ...await actual<object>(), useSdk: () => sdk, useRealtime: () => {} }));
vi.mock("../shell/data", () => ({ useTasksQuery: () => ({ data: state.queues, error: state.error, refresh: state.refresh }), useTasksRpc: () => ({ call: async (method: string, input: unknown) => { state.calls.push([method, input]); if (state.gate) await state.gate; if (state.failure) throw new Error("Order refused"); } }) }));
vi.mock("../shell/routes", () => ({ useTasksNavigation: () => ({ go: state.go }) }));
vi.mock("../shell/task-statuses", () => ({ useTaskStatuses: () => ({ label: (status: string) => status }) }));
const entry = (n: number, position = n) => ({ taskId: `task${n}`, key: `EXA-${n}`, title: `Card ${n}`, status: "todo", position });
afterEach(() => { cleanup(); state.queues = []; state.calls = []; state.failure = false; state.error = ""; state.refresh.mockReset(); state.go.mockReset(); state.gate = null; });
it("opens a card and closes the menu", async () => {
  state.queues = [{ threadId: "thr_example", entries: [entry(1)] }];
  render(<QueueMenu projectId="proj_example" />);
  fireEvent.pointerDown(screen.getByRole("button", { name: "Queue: current EXA-1 Card 1" }), { button: 0, ctrlKey: false });
  fireEvent.click(await screen.findByRole("menuitem", { name: /EXA-1 · Card 1/ }));
  expect(state.go).toHaveBeenCalledWith({ kind: "task", taskKey: "EXA-1" });
  await waitFor(() => expect(screen.queryByRole("menu")).toBeNull());
});
it("hides the trigger when there are no queues", () => { render(<QueueMenu projectId="proj_example" />); expect(screen.queryByText(/Queue/)).toBeNull(); });
it("exposes an initial read error and retries on opening", async () => {
  state.error = "Read failed";
  const { rerender } = render(<QueueMenu projectId="proj_example" />);
  fireEvent.pointerDown(screen.getByRole("button", { name: "Queue: unavailable" }), { button: 0, ctrlKey: false });
  expect((await screen.findByRole("alert")).textContent).toBe("Read failed");
  expect(state.refresh).toHaveBeenCalledOnce();
  state.error = "";
  state.queues = [{ threadId: "thr_retry", entries: [entry(1)] }];
  rerender(<QueueMenu projectId="proj_example" />);
  expect(await screen.findByRole("menuitem", { name: /EXA-1 · Card 1/ })).toBeTruthy();
});
it("shows the first next card and other queues", () => {
  state.queues = [{ threadId: "thr_first", entries: [entry(1), entry(2)] }, { threadId: "thr_second", entries: [entry(3, 1)] }];
  render(<QueueMenu projectId="proj_example" />);
  expect(screen.getByRole("button", { name: "Queue: next EXA-2 Card 2, 1 more queues" }).textContent).toContain("EXA-2 · Card 2");
  expect(screen.getByText("+1")).toBeTruthy();
});
it("moves, removes, and reports refused moves", async () => {
  state.queues = [{ threadId: "thr_first", entries: [entry(1), entry(2), entry(3)] }];
  render(<QueueMenu projectId="proj_example" />);
  fireEvent.pointerDown(screen.getByRole("button", { name: "Queue: next EXA-2 Card 2" }), { button: 0, ctrlKey: false });
  const menu = await screen.findByRole("menu");
  const item = within(menu).getByRole("menuitem", { name: /EXA-3/ });
  fireEvent.keyDown(item, { key: "ArrowUp", altKey: true });
  await waitFor(() => expect(state.calls).toContainEqual(["queueMove", { taskId: "task3", position: 2, actor: "owner" }]));
  fireEvent.click(within(menu).getByRole("button", { name: "Remove EXA-1 from the queue" }));
  await waitFor(() => expect(state.calls).toContainEqual(["queueRemove", { taskId: "task1", actor: "owner" }]));
  state.failure = true;
  fireEvent.keyDown(item, { key: "ArrowUp", altKey: true });
  expect(await within(menu).findByText("Order refused")).toBeTruthy();
  expect(screen.getByRole("menu")).toBeTruthy();
});
it("shows drag targets and only drops within the same queue", async () => {
  state.queues = [{ threadId: "thr_first", entries: [entry(1), entry(2), entry(3)] }, { threadId: "thr_second", entries: [entry(4, 1)] }];
  render(<QueueMenu projectId="proj_example" />);
  fireEvent.pointerDown(screen.getByRole("button", { name: /Queue: next EXA-2/ }), { button: 0, ctrlKey: false });
  const menu = await screen.findByRole("menu");
  const row = (key: string) => within(menu).getByRole("menuitem", { name: new RegExp(key) }).parentElement!;
  const transfer = { effectAllowed: "" };
  fireEvent.dragStart(row("EXA-3"), { dataTransfer: transfer });
  expect(row("EXA-3").className).toContain("opacity-50");
  fireEvent.dragOver(row("EXA-1"), { dataTransfer: transfer });
  expect(row("EXA-1").querySelector(".top-0")).toBeTruthy();
  fireEvent.dragOver(row("EXA-4"), { dataTransfer: transfer });
  expect(row("EXA-4").querySelector(".top-0, .bottom-0")).toBeNull();
  fireEvent.drop(row("EXA-4"), { dataTransfer: transfer });
  expect(state.calls).toHaveLength(0);
  fireEvent.dragStart(row("EXA-1"), { dataTransfer: transfer });
  fireEvent.dragOver(row("EXA-3"), { dataTransfer: transfer });
  expect(row("EXA-3").querySelector(".bottom-0")).toBeTruthy();
  fireEvent.drop(row("EXA-3"), { dataTransfer: transfer });
  await waitFor(() => expect(state.calls).toContainEqual(["queueMove", { taskId: "task1", position: 3, actor: "owner" }]));
  expect(screen.getByRole("menu")).toBeTruthy();
});
it("restores focus after keyboard move and removal", async () => {
  state.queues = [{ threadId: "thr_first", entries: [entry(1), entry(2), entry(3)] }];
  const view = render(<QueueMenu projectId="proj_example" />);
  fireEvent.pointerDown(screen.getByRole("button", { name: /Queue: next EXA-2/ }), { button: 0, ctrlKey: false });
  const menu = await screen.findByRole("menu");
  const item = (key: string) => within(menu).getByRole("menuitem", { name: new RegExp(key) });
  item("EXA-3").focus();
  fireEvent.keyDown(item("EXA-3"), { key: "ArrowUp", altKey: true });
  await waitFor(() => expect(state.refresh).toHaveBeenCalledTimes(2));
  state.queues = [{ threadId: "thr_first", entries: [entry(1), entry(3, 2), entry(2, 3)] }];
  view.rerender(<QueueMenu projectId="proj_example" />);
  expect(document.activeElement).toBe(item("EXA-3"));
  fireEvent.keyDown(item("EXA-3"), { key: "Delete" });
  await waitFor(() => expect(state.calls).toContainEqual(["queueRemove", { taskId: "task3", actor: "owner" }]));
  state.queues = [{ threadId: "thr_first", entries: [entry(1), entry(2, 2)] }];
  view.rerender(<QueueMenu projectId="proj_example" />);
  expect(document.activeElement).toBe(item("EXA-2"));
  expect(item("EXA-2").getAttribute("aria-keyshortcuts")).toBe("Alt+ArrowUp Alt+ArrowDown Delete");
});
it("does not move focus after a refused keyboard move", async () => {
  state.queues = [{ threadId: "thr_first", entries: [entry(1), entry(2), entry(3)] }];
  const view = render(<QueueMenu projectId="proj_example" />);
  fireEvent.pointerDown(screen.getByRole("button", { name: /Queue: next EXA-2/ }), { button: 0, ctrlKey: false });
  const menu = await screen.findByRole("menu");
  const item = (key: string) => within(menu).getByRole("menuitem", { name: new RegExp(key) });
  state.failure = true;
  item("EXA-3").focus();
  fireEvent.keyDown(item("EXA-3"), { key: "ArrowUp", altKey: true });
  expect(await within(menu).findByRole("alert")).toBeTruthy();
  item("EXA-1").focus();
  // A later refresh (tasks:changed) brings new data while the menu is open.
  state.queues = [{ threadId: "thr_first", entries: [entry(1), entry(2), entry(3)] }];
  view.rerender(<QueueMenu projectId="proj_example" />);
  expect(document.activeElement).toBe(item("EXA-1"));
});
it("restores focus only after the removal completes, not on a refresh while it is pending", async () => {
  state.queues = [{ threadId: "thr_first", entries: [entry(1), entry(2), entry(3)] }];
  const view = render(<QueueMenu projectId="proj_example" />);
  fireEvent.pointerDown(screen.getByRole("button", { name: /Queue: next EXA-2/ }), { button: 0, ctrlKey: false });
  const menu = await screen.findByRole("menu");
  const item = (key: string) => within(menu).getByRole("menuitem", { name: new RegExp(key) });
  let release!: () => void;
  state.gate = new Promise((resolve) => { release = resolve; });
  item("EXA-2").focus();
  fireEvent.keyDown(item("EXA-2"), { key: "Delete" });
  // An unrelated refresh lands while the removal is pending.
  state.queues = [{ threadId: "thr_first", entries: [entry(1), entry(2), entry(3)] }];
  view.rerender(<QueueMenu projectId="proj_example" />);
  expect(document.activeElement).toBe(item("EXA-2"));
  release(); state.gate = null;
  await waitFor(() => expect(state.refresh).toHaveBeenCalledTimes(2));
  // A read that started before the removal resolves after it, still with the removed card.
  state.queues = [{ threadId: "thr_first", entries: [entry(1), entry(2), entry(3)] }];
  view.rerender(<QueueMenu projectId="proj_example" />);
  expect(document.activeElement).toBe(item("EXA-2"));
  state.queues = [{ threadId: "thr_first", entries: [entry(1), entry(3, 2)] }];
  view.rerender(<QueueMenu projectId="proj_example" />);
  expect(document.activeElement).toBe(item("EXA-3"));
});
